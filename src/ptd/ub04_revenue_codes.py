def get_ub04_revenue_code_description(billing_code: str) -> Optional[str]:
    """Retrieve canonical UB-04 revenue code description."""
    c = str(billing_code).strip()
    if c in UB04_REVENUE_CODES:
        return UB04_REVENUE_CODES[c]
    # Try with or without leading zero
    c_int = str(int(c)) if c.isdigit() else c
    if c_int in UB04_REVENUE_CODES:
        return UB04_REVENUE_CODES[c_int]
    c_pad = c_int.zfill(4)
    if c_pad in UB04_REVENUE_CODES:
        return UB04_REVENUE_CODES[c_pad]
    return None
